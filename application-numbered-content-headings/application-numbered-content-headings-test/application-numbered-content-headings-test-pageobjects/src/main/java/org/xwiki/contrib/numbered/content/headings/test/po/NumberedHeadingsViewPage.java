package org.xwiki.contrib.numbered.content.headings.test.po;

import java.util.List;
import java.util.stream.Collectors;

import org.openqa.selenium.By;
import org.openqa.selenium.WebElement;
import org.xwiki.test.ui.po.ViewPage;

/**
 * The view mode of a page with numbered headings.
 *
 * @version $Id$
 * @since 1.11.1
 */
public class NumberedHeadingsViewPage extends ViewPage
{
    /**
     * @return the text of the headings of the page content that are displayed with a number
     */
    public List<String> getNumberedHeadings()
    {
        return getDriver().findElementsWithoutWaiting(By.cssSelector("#xwikicontent :is(h1, h2, h3, h4, h5, h6)"))
            .stream()
            .filter(this::isNumbered)
            .map(this::getHeadingText)
            .collect(Collectors.toList());
    }

    private boolean isNumbered(WebElement heading)
    {
        // The number is generated by a CSS counter so it is not part of the heading text.
        String content = (String) getDriver().executeScript(
            "return window.getComputedStyle(arguments[0], '::before').getPropertyValue('content');", heading);
        return content.contains("counter(");
    }

    private String getHeadingText(WebElement heading)
    {
        String text = heading.getText();
        for (WebElement sectionEditLink : getDriver().findElementsWithoutWaiting(heading,
            By.className("edit_section"))) {
            text = text.replace(sectionEditLink.getText(), "");
        }
        return text.trim();
    }
}
